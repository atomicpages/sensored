#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_lowercase_and_unique() {
        for list in [HONORIFICS, PARTICLES, FUNCTION_WORDS, NON_NAME_WORDS] {
            assert!(list.windows(2).all(|pair| pair[0] < pair[1]), "{list:?}");
            assert!(list.iter().all(|word| *word == word.to_ascii_lowercase()));
        }
    }
}
